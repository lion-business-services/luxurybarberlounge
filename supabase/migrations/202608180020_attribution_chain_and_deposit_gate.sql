alter table public.booking_metadata
  add column if not exists appointment_id uuid references public.appointments(id) on delete cascade;

create unique index if not exists booking_metadata_appointment_id_key
  on public.booking_metadata(appointment_id)
  where appointment_id is not null;

create index if not exists booking_attributions_metadata_idx
  on public.booking_attributions(booking_metadata_id);

alter table public.appointments
  add column if not exists client_declared_status text
    check (client_declared_status in ('new','existing','unsure'));

